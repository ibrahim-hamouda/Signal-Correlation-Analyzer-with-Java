    private void btnUpload1ActionPerformed(java.awt.event.ActionEvent evt) {

    JFileChooser chooser = new JFileChooser();
    // 1. We added "wav" to the allowed list here
    chooser.setFileFilter(new FileNameExtensionFilter("Signal & Audio Files", "txt", "csv", "wav"));
    
    int returnVal = chooser.showOpenDialog(this);
    if(returnVal == JFileChooser.APPROVE_OPTION) {
        String filePath = chooser.getSelectedFile().getAbsolutePath();
        System.out.println("Signal 1 Path: " + filePath);
        
        // 2. Route the file to the correct loader based on its extension
        if (filePath.toLowerCase().endsWith(".wav")) {
            signal1Data = AudioSignalLoader.loadWav(filePath);
        } else if (filePath.toLowerCase().endsWith(".csv")) {
            signal1Data = SignalLoader.loadCSV(filePath);
        } else {
            signal1Data = SignalLoader.loadTXT(filePath); 
        }
        
        jLabel1.setText("Signal 1 Loaded! Size: " + signal1Data.length);
    }
    

    }

