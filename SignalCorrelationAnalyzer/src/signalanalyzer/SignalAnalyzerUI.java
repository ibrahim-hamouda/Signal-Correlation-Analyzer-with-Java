    private void btnAnalyzeActionPerformed(java.awt.event.ActionEvent evt) {
        // Safety check
    if (signal1Data == null || signal2Data == null) {
        System.out.println("Please upload both signals first!");
        return;
    }

    // 1. Tell the user it is working and DISABLE the button so they don't click it twice
    jLabel4.setText("Status: Processing audio... Please wait!");
    btnAnalyze.setEnabled(false); 

    // 2. Push the heavy math to a Background Thread so the UI doesn't freeze
    new Thread(() -> {
        try {
            // Call Mukhtar's Math Engine
            double[] correlationResult = signal_correlation.computeCorrelation(signal1Data, signal2Data);

            // Call Ahmed Youssef's Logic
            int lag = Analyzer.findLag(signal1Data, signal2Data);
            double similarity = Analyzer.calcSimilarity(signal1Data, signal2Data);

            // 3.Push the results back to the Main UI Thread
            javax.swing.SwingUtilities.invokeLater(() -> {
                jLabel3.setText(String.format("Similarity: %.1f%%", similarity));
                jLabel4.setText("Status: Delayed by " + lag + " steps");
                btnAnalyze.setEnabled(true); // Turn the button back on

                // Call Ismail's Visualizer
                SignalVisualizer visualizer = new SignalVisualizer();
                visualizer.showCharts(signal1Data, signal2Data, correlationResult);
            });

        } catch (Exception e) {
            System.out.println("Error during calculation: " + e.getMessage());
        }
    }).start();
    }

